import { Capacitor } from '@capacitor/core';
import { Filesystem, Directory } from '@capacitor/filesystem';
import { Share } from '@capacitor/share';
import jsPDF from 'jspdf';
import Swal from 'sweetalert2';

/**
 * Universal Mobile & Web PDF Downloader & Sharer
 * Handles Capacitor Android/iOS WebView sandboxing as well as standard desktop browsers.
 */
export async function downloadOrSharePdf(
  pdf: jsPDF,
  filename: string,
  title: string = 'Medical Document'
): Promise<void> {
  const isNative = Capacitor.isNativePlatform();

  try {
    if (isNative) {
      // In Native Android / iOS, convert to Base64 and write to device Filesystem
      const pdfBase64 = pdf.output('datauristring').split(',')[1];
      const cleanFileName = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;

      try {
        const savedFile = await Filesystem.writeFile({
          path: cleanFileName,
          data: pdfBase64,
          directory: Directory.Documents,
          recursive: true,
        });

        // Open native share sheet so user can view, print, or send via WhatsApp/Drive/Gmail
        await Share.share({
          title: title,
          text: `${title} - Generated by Dr. Priya Clinical Assistant`,
          url: savedFile.uri,
          dialogTitle: `Open or Share ${cleanFileName}`,
        });

        Swal.fire({
          icon: 'success',
          title: 'PDF Saved & Shared!',
          text: `Document saved to Documents/${cleanFileName}`,
          timer: 3000,
          showConfirmButton: false,
          toast: true,
          position: 'top-end',
        });
        return;
      } catch (shareErr) {
        console.warn('Capacitor native share/filesystem fallback:', shareErr);
        // Fallback to data URI link navigation
        const dataUri = pdf.output('datauristring');
        const link = document.createElement('a');
        link.href = dataUri;
        link.download = cleanFileName;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
      }
    } else {
      // Standard browser download
      pdf.save(filename);
      Swal.fire({
        icon: 'success',
        title: 'PDF Downloaded!',
        text: `File saved as ${filename}`,
        timer: 2500,
        showConfirmButton: false,
        toast: true,
        position: 'top-end',
      });
    }
  } catch (error: any) {
    console.error('Download/Share PDF Error:', error);
    // Ultimate fallback: open print window
    window.print();
  }
}
